const questions = [];
const blocks = inputMd.split(/---\n+/);

blocks.forEach(block => {
  const qMatch = block.match(/## प्रश्न (\d+) \((.*?)\)/);
  if (!qMatch) return;

  const id = parseInt(qMatch[1], 10);
  const qType = qMatch[2].trim();

  const subjectMatch = block.match(/\*\*विषय:\s*(.*?)\*\*/);
  const subject = subjectMatch ? subjectMatch[1].trim() : '';

  const optMatch = block.match(/\*\*विकल्प:\*\*\n([\s\S]*?)\n\n\*\*सही उत्तर:/);
  const optionsRaw = optMatch ? optMatch[1] : '';
  const options = optionsRaw.split('\n').filter(l => l.trim().startsWith('*')).map(l => l.replace(/^\*\s*/, '').trim());

  const ansMatch = block.match(/\*\*सही उत्तर:\s*\[([A-D])\]\*\*/);
  const answer = ansMatch ? ansMatch[1] : '';

  const expMatch = block.match(/\*\*विस्तृत व्याख्या:\*\*\s*\n?([\s\S]*)$/);
  const explanation = expMatch ? expMatch[1].trim() : '';

  // Extract the question content (everything between subject and options)
  const qBodyMatch = block.match(/\*\*विषय:.*?\*\*\n+([\s\S]*?)\n+\*\*विकल्प:\*\*/);
  let questionText = qBodyMatch ? qBodyMatch[1].trim() : '';

  // For tables, we need to convert them to HTML if any or keep as Markdown? The quiz engine supports HTML in questions, but also the existing format uses custom matching layout.
  // Wait, looking at the previous file's `renderStructuredQuestion`, it expects:
  // - matching: "सूची-I (साहित्यिक कृति) को सूची-II (लेखक/साहित्यकार) के साथ सुमेलित कीजिए:\n\nसूची-I (कृति):\n1. ...\n\nसूची-II (लेखक):\nI. ...\n\nकूट:"
  // - assertion-reason: "कथन (A): ...\n\nकारण (R): ..."
  // - multi-statement: "1. ...\n2. ...\n\nऊपर दिए गए कथनों में से कौन से सही हैं?"
  // - statement-conclusion: "कथन: ...\n\nनिष्कर्ष:\n1. ...\n2. ..."

  // Let's format `questionText` to match the expected format for the engine.
  // Replace Markdown table with the expected string format for Matching.
  if (qType.includes('Matching Type') || qType.includes('मिलान वाले प्रश्न')) {
    // Convert MD table to standard list for matching.
    const tableRegex = /\|\s*सूची-I.*?\n\|.*?\n([\s\S]*)/;
    const tableMatch = questionText.match(tableRegex);
    if (tableMatch) {
      const rows = tableMatch[1].split('\n').filter(r => r.trim().startsWith('|'));
      let list1 = [];
      let list2 = [];
      rows.forEach(row => {
        const cols = row.split('|').map(c => c.trim()).filter(c => c !== '');
        if (cols.length === 2) {
          list1.push(cols[0].replace(/\*\*/g, ''));
          list2.push(cols[1].replace(/\*\*/g, ''));
        }
      });
      questionText = questionText.replace(tableRegex, `सूची-I:\n${list1.join('\n')}\n\nसूची-II:\n${list2.join('\n')}\n\nकूट:`);
    } else {
        // Just append कूट: at the end if it's a matching question without table but structured as lists
        if (!questionText.includes('कूट:')) {
            questionText += '\n\nकूट:';
        }
    }
  }

  // Remove bold markdown from questionText
  questionText = questionText.replace(/\*\*(.*?)\*\*/g, '$1');
  // Remove markdown list bullets if they are just *
  questionText = questionText.replace(/^\*\s+कथन \(A\):/m, 'कथन (A):');
  questionText = questionText.replace(/^\*\s+कारण \(R\):/m, 'कारण (R):');
  questionText = questionText.replace(/^\*\s+कथन:/m, 'कथन:');
  questionText = questionText.replace(/^\*\s+निष्कर्ष:/m, 'निष्कर्ष:');

  // Same for options
  const cleanOptions = options.map(o => o.replace(/\*\*(.*?)\*\*/g, '$1'));

  questions.push({
    id,
    section: subject,
    questionType: qType,
    difficulty: "advanced",
    topic: subject,
    question: questionText,
    options: cleanOptions,
    answer,
    explanation
  });
});

